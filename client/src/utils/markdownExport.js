/**
 * Generates and downloads a formatted Markdown audit report.
 */

const STATUS_ICONS = {
  matched: '✅',
  weakly_demonstrated: '⚠️',
  missing: '❌',
};

const EFFORT_ICONS = {
  Low: '🟢',
  Medium: '🟡',
  High: '🔴',
};

/**
 * Generates a full Markdown report string from an audit result.
 * @param {object} auditResult
 * @param {string} [jobTitle]
 * @returns {string}
 */
export function generateMarkdownReport(auditResult, jobTitle = 'Target Role') {
  const date = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const lines = [
    '# ResumeMate AI — Alignment Audit Report',
    '',
    `> **Generated:** ${date}`,
    `> **Target Role:** ${jobTitle}`,
    `> **Tool:** ResumeMate AI v1.0 — Privacy-first, stateless audit`,
    '',
    '---',
    '',
    `## Overall Score: ${auditResult.overall_score} / 100 — Grade: ${auditResult.grade}`,
    '',
    '## Executive Summary',
    '',
    auditResult.executive_summary || '',
    '',
    '---',
    '',
    '## Scoring Rubric Breakdown',
    '',
    '| Pillar | Earned | Max | % | Justification |',
    '|--------|--------|-----|---|---------------|',
    ...(auditResult.pillars || []).map((p) => {
      const pct = Math.round((p.earned_points / p.max_points) * 100);
      return `| ${p.label} | **${p.earned_points}** | ${p.max_points} | ${pct}% | ${p.justification} |`;
    }),
    '',
    '---',
    '',
    '## Skill Matrix',
    '',
    '| Skill | Status | Evidence Quote | Gap Notes |',
    '|-------|--------|----------------|-----------|',
    ...(auditResult.skill_matrix || []).map((s) => {
      const icon = STATUS_ICONS[s.status] || '';
      const label = s.status.replace(/_/g, ' ');
      const quote = s.evidence_quote ? `\`${s.evidence_quote.slice(0, 80)}…\`` : '—';
      const gap = s.gap_explanation || '—';
      return `| ${s.skill} | ${icon} ${label} | ${quote} | ${gap} |`;
    }),
    '',
    '---',
    '',
    '## Bullet Rewrites',
    '',
    ...(auditResult.bullet_rewrites || []).flatMap((b, i) => [
      `### Rewrite ${i + 1}`,
      '',
      '**Original:**',
      `> ${b.original}`,
      '',
      '**Improved (XYZ Format):**',
      `> ${b.improved}`,
      '',
      `**Rationale:** ${b.rationale}`,
      '',
      `**Keywords added:** ${(b.keywords_added || []).map((k) => `\`${k}\``).join(', ')}`,
      '',
      '---',
      '',
    ]),
    '## Action Plan',
    '',
    ...(auditResult.action_plan || []).map((a) => {
      const effort = EFFORT_ICONS[a.effort] || '';
      return `${a.rank}. ${effort} **[${a.effort} effort · +${a.score_lift_pts} pts]** ${a.action}`;
    }),
    '',
    '---',
    '',
    '*Generated by ResumeMate AI — Privacy-first, stateless resume alignment audit. No data is stored.*',
  ];

  return lines.join('\n');
}

/**
 * Triggers a browser download of the Markdown report.
 * @param {object} auditResult
 * @param {string} [jobTitle]
 */
export function downloadMarkdownReport(auditResult, jobTitle = 'Target Role') {
  const markdown = generateMarkdownReport(auditResult, jobTitle);
  const blob = new Blob([markdown], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'resumemate-audit.md';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
